#!/usr/bin/env python3
"""CI regression guard: a rare Hangul syllable must not cost a day's digest.

Why this guard exists
---------------------
On 2026-11-20 the cron digest contained one syllable (댤) outside KS X 1001.
``test_every_corpus_syllable_is_covered_by_a_shipped_tier`` failed inside the
"Corpus gate pre-flight (block)" step and the whole post was discarded, although
the test's own message names the deterministic fix:
``generate_noto_2tier_subset.py --only-tier2`` (about 17 s, rewrites only the
two tier-2 woff2 files and ``assets/css/font-tier2.css``).

The workflow now runs that regeneration as a self-heal step before the corpus
gate and stages the three files into the digest commit. This guard fails if the
regen call, its ordering, or the ``git add`` disappears.

It also pins the schedule: a primary run off the top of the hour (the 00:00 UTC
slot was regularly delayed 3-5 h and once 19 h, which moved the 11-17 digest to
11-18) plus a same-day retry. Both must stay inside 00:00-14:59 UTC so the KST
filename date and the UTC permalink date agree; the retry is a no-op when the
day's post exists (``same_day_exists``).
"""

from __future__ import annotations

import re
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]
WORKFLOW = REPO_ROOT / ".github" / "workflows" / "ai-blogwatcher.yml"
REGEN = re.compile(
    r"python3?\s+scripts/build/generate_noto_2tier_subset\.py\s+--only-tier2"
)
TIER2_FILES = (
    "assets/css/font-tier2.css",
    "assets/fonts/noto-sans-kr-400-tier2.woff2",
    "assets/fonts/noto-sans-kr-700-tier2.woff2",
)


def _noncomment_lines(text: str) -> str:
    return "\n".join(ln for ln in text.splitlines() if not ln.lstrip().startswith("#"))


def _body() -> str:
    return _noncomment_lines(WORKFLOW.read_text(encoding="utf-8"))


def test_tier2_regen_runs_before_the_corpus_gate():
    body = _body()
    regen = REGEN.search(body)
    gate = body.find("name: Corpus gate pre-flight (block)")
    assert regen, (
        "font tier-2 self-heal (generate_noto_2tier_subset.py --only-tier2) is gone"
    )
    assert gate != -1, "corpus gate step renamed; update this guard"
    assert regen.start() < gate, "font self-heal must run before the corpus gate pytest"


def test_regenerated_tier2_files_are_staged_into_the_digest_commit():
    body = _body()
    commit = body.find("name: Commit and publish")
    staged = body[commit:]
    for path in TIER2_FILES:
        assert re.search(rf"git add\b[^\n]*{re.escape(path)}", staged), (
            f"{path} is regenerated by the self-heal but not staged in 'Commit and publish'"
        )


def test_schedule_is_off_the_hour_with_a_same_day_retry():
    on = yaml.safe_load(WORKFLOW.read_text(encoding="utf-8"))[True]
    crons = [entry["cron"] for entry in on["schedule"]]
    assert len(crons) == 2, crons
    for cron in crons:
        minute, hour = cron.split()[:2]
        assert minute != "0", (
            f"{cron}: the top of the hour is GitHub's most delayed slot"
        )
        assert 0 <= int(hour) <= 14, (
            f"{cron}: must stay inside the same KST and UTC date"
        )
